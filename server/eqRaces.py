def spawnScale(code, height, newEngineZone):
  """The scale eqgame.exe 0x5a3f40 draws a spawn of this height at: WLD models at height / 5, 1.3 times smaller in a NewEngineZone
  zone, and EQG models at height / 6, 1.3 times larger outside one."""
  if code not in registeredCodes:
    raise ValueError(f"eqgame.exe registers no race with the model {code}, so the client never draws a spawn with it")
  if height <= 0:
    raise ValueError(f"height must be positive, got {height}")
  if code in eqgModelCodes:
    return height / 6 if newEngineZone else height * 1.3 / 6
  return height * 0.2 / 1.3 if newEngineZone else height * 0.2


def avatarOffsets(clientRoot):
  """Resources/moddat.ini ROffset by model code."""
  iniPath = clientRoot / "Resources" / "moddat.ini"
  if not iniPath.is_file():
    raise ValueError(f"The client has no {iniPath}")
  settings = configparser.ConfigParser(interpolation=None, strict=False)
  settings.read_string(iniPath.read_text(encoding="latin1"))
  return {section.upper(): float(settings[section]["ROffset"]) for section in settings.sections() if "ROffset" in settings[section]}


def avatarHeight(clientRoot, code, scale):
  """How high the client stands a spawn's model origin above the ground (0x5a3f40): moddat.ini's ROffset for the model, else 3.125, times its scale."""
  return avatarOffsets(clientRoot).get(code, defaultAvatarOffset) * scale
